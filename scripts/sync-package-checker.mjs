#!/usr/bin/env node
// Vendor package-checker.sh (https://github.com/maxgfr/package-checker.sh) at a
// release tag (or, before a release, a branch or commit), pinned by sha256 and
// by the resolved commit, and render it as a TypeScript string so the bundle
// carries it: scan deps then runs with no download of the script.
//
//   node scripts/sync-package-checker.mjs --ref v1.16.4   pin a release tag and render
//   node scripts/sync-package-checker.mjs --ref <branch|commit>   pin that commit (pre-release)
//   node scripts/sync-package-checker.mjs --check         offline drift gate (CI)
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const SH = "src/vendor/package-checker.sh";
const TS = "src/vendor/package-checker-script.ts";
const META = "src/vendor/package-checker.meta.json";
const sha = (b) => createHash("sha256").update(b).digest("hex");
const label = (meta) => (meta.commit && meta.ref !== `v${meta.version}` ? `${meta.ref}@${meta.commit.slice(0, 7)}` : meta.ref);
const render = (script, meta) =>
  `// GENERATED by scripts/sync-package-checker.mjs from ${SH} (${label(meta)}). Do not edit.\nexport const PACKAGE_CHECKER_VERSION = ${JSON.stringify(meta.version)};\nexport const PACKAGE_CHECKER_REF = ${JSON.stringify(label(meta))};\nexport const PACKAGE_CHECKER_SHA256 = ${JSON.stringify(meta.sha256)};\nexport const PACKAGE_CHECKER_SCRIPT = ${JSON.stringify(script)};\n`;

const args = process.argv.slice(2);
if (args[0] === "--check") {
  if (!existsSync(META) || !existsSync(SH) || !existsSync(TS)) {
    console.error("sync-package-checker: DRIFT, vendored files missing: run --ref <tag>");
    process.exit(1);
  }
  const meta = JSON.parse(readFileSync(META, "utf8"));
  const script = readFileSync(SH, "utf8");
  if (sha(script) !== meta.sha256) {
    console.error(`sync-package-checker: DRIFT, ${SH} differs from the ${label(meta)} pin`);
    process.exit(1);
  }
  if (readFileSync(TS, "utf8") !== render(script, meta)) {
    console.error(`sync-package-checker: DRIFT, ${TS} is not a fresh render of ${SH}`);
    process.exit(1);
  }
  console.log(`sync-package-checker: ok, ${label(meta)} (${meta.sha256.slice(0, 12)})`);
  process.exit(0);
}
if (args[0] !== "--ref" || !args[1]) {
  console.error("usage: sync-package-checker.mjs --ref <tag|branch|commit> | --check");
  process.exit(2);
}
const ref = args[1];
// The commit the ref names now: a branch moves, the pin must not.
const head = await fetch(`https://api.github.com/repos/maxgfr/package-checker.sh/commits/${encodeURIComponent(ref)}`, {
  headers: { accept: "application/vnd.github.sha" },
});
const commit = head.ok ? (await head.text()).trim() : "";
if (!/^[0-9a-f]{40}$/.test(commit)) {
  console.error(`sync-package-checker: cannot resolve ${ref} to a commit (HTTP ${head.status})`);
  process.exit(1);
}
const res = await fetch(`https://raw.githubusercontent.com/maxgfr/package-checker.sh/${commit}/script.sh`);
if (!res.ok) {
  console.error(`sync-package-checker: HTTP ${res.status} for ${ref} (${commit})`);
  process.exit(1);
}
const script = await res.text();
const version = /^VERSION="([^"]+)"/m.exec(script)?.[1];
// A release tag must be the version the script says; a branch or commit is a pre-release pin.
if (!version || (/^v\d/.test(ref) && `v${version}` !== ref)) {
  console.error(`sync-package-checker: the script says VERSION=${version ?? "?"}, the ref is ${ref}`);
  process.exit(1);
}
const meta = { ref, commit, version, sha256: sha(script), syncedAt: new Date().toISOString() };
writeFileSync(SH, script);
writeFileSync(META, `${JSON.stringify(meta, null, 2)}\n`);
writeFileSync(TS, render(script, meta));
console.log(`sync-package-checker: pinned ${label(meta)} (${meta.sha256.slice(0, 12)})`);
