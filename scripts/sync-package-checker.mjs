#!/usr/bin/env node
// Vendor package-checker.sh (https://github.com/maxgfr/package-checker.sh) at a
// release tag, pinned by sha256, and render it as a TypeScript string so the
// bundle carries it: scan deps then runs with no download of the script.
//
//   node scripts/sync-package-checker.mjs --ref v1.16.4   pin and render
//   node scripts/sync-package-checker.mjs --check         offline drift gate (CI)
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const SH = "src/vendor/package-checker.sh";
const TS = "src/vendor/package-checker-script.ts";
const META = "src/vendor/package-checker.meta.json";
const sha = (b) => createHash("sha256").update(b).digest("hex");
const render = (script, meta) =>
  `// GENERATED by scripts/sync-package-checker.mjs from ${SH} (${meta.tag}). Do not edit.\nexport const PACKAGE_CHECKER_VERSION = ${JSON.stringify(meta.version)};\nexport const PACKAGE_CHECKER_SHA256 = ${JSON.stringify(meta.sha256)};\nexport const PACKAGE_CHECKER_SCRIPT = ${JSON.stringify(script)};\n`;

const args = process.argv.slice(2);
if (args[0] === "--check") {
  if (!existsSync(META) || !existsSync(SH) || !existsSync(TS)) {
    console.error("sync-package-checker: DRIFT, vendored files missing: run --ref <tag>");
    process.exit(1);
  }
  const meta = JSON.parse(readFileSync(META, "utf8"));
  const script = readFileSync(SH, "utf8");
  if (sha(script) !== meta.sha256) {
    console.error(`sync-package-checker: DRIFT, ${SH} differs from the ${meta.tag} pin`);
    process.exit(1);
  }
  if (readFileSync(TS, "utf8") !== render(script, meta)) {
    console.error(`sync-package-checker: DRIFT, ${TS} is not a fresh render of ${SH}`);
    process.exit(1);
  }
  console.log(`sync-package-checker: ok, ${meta.tag} (${meta.sha256.slice(0, 12)})`);
  process.exit(0);
}
if (args[0] !== "--ref" || !args[1]) {
  console.error("usage: sync-package-checker.mjs --ref <tag> | --check");
  process.exit(2);
}
const ref = args[1];
const res = await fetch(`https://raw.githubusercontent.com/maxgfr/package-checker.sh/${ref}/script.sh`);
if (!res.ok) {
  console.error(`sync-package-checker: HTTP ${res.status} for ${ref}`);
  process.exit(1);
}
const script = await res.text();
const version = /^VERSION="([^"]+)"/m.exec(script)?.[1];
if (!version || `v${version}` !== ref) {
  console.error(`sync-package-checker: the script says VERSION=${version ?? "?"}, the ref is ${ref}`);
  process.exit(1);
}
const meta = { tag: ref, version, sha256: sha(script), syncedAt: new Date().toISOString() };
writeFileSync(SH, script);
writeFileSync(META, `${JSON.stringify(meta, null, 2)}\n`);
writeFileSync(TS, render(script, meta));
console.log(`sync-package-checker: pinned ${ref} (${meta.sha256.slice(0, 12)})`);
